// i18n do Python AI Dojo — idioma da interface (pt | en).
//
// t(chave, vars) devolve o texto do idioma atual; vars substitui {nome} no
// texto (só \{\w+\}: "{ }" literal fica intacto). Valores de dicionário são
// TEXTO CONFIÁVEL (podem ter <strong>/<em>); quem passa dado do save/conteúdo
// em vars para um innerHTML escapa antes (esc/num do ui.js), como sempre.
// Chave ausente no idioma -> cai no pt -> cai na própria chave (nunca quebra).
//
// O conteúdo (exercícios) NÃO mora aqui: content/*.json é pt, content/en/*.json
// é en (mesmos ids). Ver content.js e tools/i18n_check.py.

import { GLOSSARIO } from "./glossario.js";
import { GLOSSARIO_EN } from "./glossario-en.js";

export const IDIOMAS = ["pt", "en"];
let LANG = "pt";

// pt* -> pt; qualquer outra coisa -> en
export function detectarIdioma(nav = (typeof navigator !== "undefined" ? navigator : null)) {
  const lista = (nav && (nav.languages && nav.languages.length ? nav.languages : [nav.language])) || [];
  const primeiro = String(lista[0] || "").toLowerCase();
  return primeiro.startsWith("pt") ? "pt" : "en";
}

export function idiomaValido(l) {
  return IDIOMAS.includes(l);
}

export function definirIdioma(l) {
  LANG = idiomaValido(l) ? l : "pt";
  if (typeof document !== "undefined" && document.documentElement) {
    document.documentElement.lang = LANG === "en" ? "en" : "pt-BR";
  }
  return LANG;
}

export function idioma() {
  return LANG;
}

export function glossario() {
  return LANG === "en" ? GLOSSARIO_EN : GLOSSARIO;
}

// Plural: {n|singular|plural} escolhe pela variável n (=== 1 -> singular).
// Ex.: "{n} {n|test|tests} passed". Sem a variável, fica intacto.
export function t(chave, vars) {
  let s = DIC[LANG][chave];
  if (s === undefined) s = DIC.pt[chave];
  if (s === undefined) return chave;
  if (typeof s !== "string" || !vars) return s;
  return s
    .replace(/\{(\w+)\|([^|{}]*)\|([^|{}]*)\}/g, (m, k, um, varios) =>
      (k in vars ? (Number(vars[k]) === 1 ? um : varios) : m))
    .replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

